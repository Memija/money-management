export function generateCsvTestFiles(csvDir) {
  fs.mkdirSync(csvDir, { recursive: true })
  for (const setup of CSV_FORMAT_SETUPS) {
    fs.writeFileSync(path.join(csvDir, `${setup.id}.csv`), setup.content + '\n', 'utf-8')
  }
  return CSV_FORMAT_SETUPS.length
}
